import {readFileSync,writeFileSync} from 'node:fs';
import {createTrafficNetwork,PLANE_STYLES} from '../components/three/air-traffic/traffic-network.mjs';
import {createHexagonalEarthGeometry} from '../components/three/planet/hexagonal-earth-geometry.mjs';
import {createAirplaneModel} from '../components/three/air-traffic/airplane-model.mjs';
import {Vector3} from 'three';
// Offline conservative swept-sphere corridor: includes the complete jet, tile corners and peak waves.
const earth=JSON.parse(readFileSync(new URL('../public/models/earth/block-earth.json',import.meta.url))),airports=JSON.parse(readFileSync(new URL('../components/three/air-traffic/major-airports.json',import.meta.url))),network=createTrafficNetwork(airports),tile=createHexagonalEarthGeometry(),plane=createAirplaneModel();
tile.computeBoundingSphere();const planeRadius=plane.geometry.boundingSphere.radius*.13*Math.max(...PLANE_STYLES.map(s=>s.size));
const cells=earth.sizes.map((size,i)=>{const center=new Vector3().fromArray(earth.positions,i*3),length=center.length(),radius=tile.boundingSphere.radius*size*1.4+(earth.oceanMask[i]?.055:0);return {direction:center.divideScalar(length),length,radius};});
const result={},tangent=new Vector3();
for(const route of network.routes){
 tangent.crossVectors(route.axis,route.start);let height=3.16;
 for(const cell of cells){
  const x=cell.direction.dot(route.start),y=cell.direction.dot(tangent),angle=Math.atan2(y,x);
  const nearest=Math.max(x,cell.direction.dot(route.end),angle>=0&&angle<=route.angle?Math.hypot(x,y):-1);
  const margin=Math.asin(Math.min(1,(cell.radius+planeRadius+.025)/cell.length));
  if(nearest>=Math.cos(margin))height=Math.max(height,cell.length+cell.radius+planeRadius+.025);
 }
 result[`${route.from}:${route.to}`]=Math.ceil(height*10000)/10000;
}
writeFileSync(new URL('../components/three/air-traffic/route-clearances.mjs',import.meta.url),'// Generated by scripts/generate-flight-clearances.mjs from the actual terrain and jet geometry.\nexport const ROUTE_CLEARANCES='+JSON.stringify(result)+';\n');
console.log({routes:network.routes.length,min:Math.min(...Object.values(result)),max:Math.max(...Object.values(result)),planeRadius});tile.dispose();plane.dispose();
